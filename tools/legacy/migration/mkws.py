#!/usr/bin/env python3
"""Generate the Triple A Sweeper workspace from the single-file template (one-off migration script)."""
import base64, glob, json, os, re, shutil, subprocess

SP = '/tmp/claude-0/-home-claude/d78743a1-6a1d-564d-bbd8-066f6fc59d0d/scratchpad/'
WS = '/home/claude/triple-a-sweeper/'
os.makedirs(WS, exist_ok=True)

src = open(SP + 'template.html').read()

# ---------------------------------------------------------------- JS modules
if os.path.exists(WS + 'js'):
    shutil.rmtree(WS + 'js')
subprocess.run(['node', 'extract.mjs'], cwd=SP + 'split', check=True)
r = subprocess.run(['node', 'split.mjs', WS + 'js'], cwd=SP + 'split', check=True, capture_output=True, text=True)
print(r.stdout[-600:])
assert 'HAZARDS none' in r.stdout

# voice manifest (metadata only; audio goes to public/voices)
voices = {}
for fn in ['voices.json', 'voices2.json', 'voices3.json', 'voices4.json']:
    for k, x in json.load(open(SP + 'tts/' + fn)).items():
        e = {'d': x['d']}
        if 'w' in x:
            e['w'] = x['w']; e['t'] = x['t']
        voices[k] = (e, x['b64'], fn)
lines = [f'{json.dumps(k)}:{json.dumps(voices[k][0], ensure_ascii=False, separators=(",", ":"))},' for k in sorted(voices)]
open(WS + 'js/data/voice-manifest.js', 'w').write(
    '// data/voice-manifest.js — GENERATED by tools/tts/generate_voices.py. Do not edit by hand.\n'
    '// One entry per voice line: d = duration in seconds, w = speaker key, t = subtitle text.\n'
    '// Lines of the first batch have no w/t: their speaker comes from the id prefix (PREFIX) and\n'
    '// their subtitle from SUBS in data/dialogue.js. Audio files live in public/voices/<id>.mp3.\n'
    'export const VOICES={\n' + '\n'.join(lines) + '\n};\n')

# audio files
vdir = WS + 'public/voices/'
if os.path.exists(vdir):
    shutil.rmtree(vdir)
os.makedirs(vdir)
for k, (e, b64, fn) in voices.items():
    open(vdir + k + '.mp3', 'wb').write(base64.b64decode(b64))
print('voices', len(voices))

# voice-bank: fetch files instead of decoding embedded base64
vb = WS + 'js/audio/voice-bank.js'
s = open(vb).read()
old = "    try{const p=A.ctx.decodeAudioData(b64ToBuf(v.b64),ok,bad);if(p&&p.then)p.then(ok,bad);}catch(e){bad();}});"
new = "    loadVoiceData(id).then(buf=>{const p=A.ctx.decodeAudioData(buf,ok,bad);if(p&&p.then)p.then(ok,bad);}).catch(bad);});"
assert s.count(old) == 1
s = s.replace(old, new)
anchor = 'export function decodeOne(id){'
assert s.count(anchor) == 1
s = s.replace(anchor, '''// Voice audio comes from public/voices/<id>.mp3. The single-file build (tools/build/build-single.mjs)
// inlines every file as base64 into window.__VOICE_B64 instead, so the page works without a server.
export const voiceUrl=id=>`voices/${id}.mp3`;
function loadVoiceData(id){const inl=globalThis.__VOICE_B64;if(inl&&inl[id])return Promise.resolve(b64ToBuf(inl[id]));
  return fetch(voiceUrl(id)).then(r=>{if(!r.ok)throw new Error('voice '+id+': HTTP '+r.status);return r.arrayBuffer();});}
''' + anchor)
open(vb, 'w').write(s)

# main: optional debug hooks
mp = WS + 'js/main.js'
s = open(mp).read()
s += "\n// Test and tooling hooks (window.__t, window.__render) are only loaded with ?debug in the URL.\nif(new URLSearchParams(location.search).has('debug'))import('./debug.js');\n"
open(mp, 'w').write(s)

# ---------------------------------------------------------------- CSS
css = src[src.index('<style>') + 7:src.index('</style>')]
marks = [('base', None), ('desktop', '/* ---------- Win98 desktop'), ('intro', '/* ---------- Intro'), ('title', '/* ---------- Title'),
         ('game', '/* ---------- Game'), ('overlays', '/* global HUD-ish overlays */'), ('credits', '/* credits */'), ('layouts', '/* layouts chosen by script */')]
pos = [0] + [css.index(m) for _, m in marks[1:]] + [len(css)]
if os.path.exists(WS + 'css'):
    shutil.rmtree(WS + 'css')
os.makedirs(WS + 'css')
cssfiles = []
for i, (name, _) in enumerate(marks):
    part = css[pos[i]:pos[i + 1]].strip('\n') + '\n'
    open(WS + f'css/{name}.css', 'w').write(part)
    cssfiles.append(name)

# fonts (self-hosted copies of the Google Fonts used by the game; SIL OFL 1.1)
FONTS = [('Audiowide', 'audiowide', [400]), ('Caveat', 'caveat', [600, 700]), ('Chakra Petch', 'chakra-petch', [400, 500, 600, 700]),
         ('Cinzel', 'cinzel', [600, 800]), ('Michroma', 'michroma', [400]), ('Russo One', 'russo-one', [400]), ('Teko', 'teko', [400, 500, 600])]
fdir = WS + 'assets/fonts/'
if os.path.exists(fdir):
    shutil.rmtree(fdir)
os.makedirs(fdir)
fcss = ['/* Self-hosted copies of the Google Fonts the game uses (latin + latin-ext subsets).',
        ' * Source: Fontsource npm packages. Licence: SIL Open Font License 1.1, see assets/fonts/LICENSES/.',
        ' * The single-file build swaps this file for the Google Fonts <link> (see tools/build/build-single.mjs). */', '']
os.makedirs(fdir + 'LICENSES')
for fam, slug, weights in FONTS:
    pk = (glob.glob(SP + f'fonts/fontsource-{slug}-*/package') + glob.glob(SP + f'fonts/fontsource-{slug}/package'))[0]
    shutil.copy(pk + '/LICENSE', fdir + f'LICENSES/{slug}-OFL.txt')
    for w in weights:
        for blk in open(pk + f'/{w}.css').read().split('/* ')[1:]:
            head = blk.split(' */')[0]
            if not (head.endswith(f'-latin-{w}-normal') or head.endswith(f'-latin-ext-{w}-normal')):
                continue
            body = '/* ' + blk.strip()
            m = re.search(r"url\(\./files/([^)]+\.woff2)\)", body)
            shutil.copy(pk + '/files/' + m.group(1), fdir + m.group(1))
            body = re.sub(r"src: url\(\./files/([^)]+\.woff2)\) format\('woff2'\), url\([^)]+\) format\('woff'\);",
                          r"src: url(../assets/fonts/\1) format('woff2');", body)
            assert '../assets/fonts/' in body, body
            fcss.append(body + '\n')
open(WS + 'css/fonts.css', 'w').write('\n'.join(fcss))

# ---------------------------------------------------------------- index.html
body = src[src.index('</style>') + 8:src.index('<script>')].strip('\n')
sym = body[body.index('<symbol id="i-mine"'):]
sym = sym[sym.index('>') + 1:sym.index('</symbol>')]
open(WS + 'public/favicon.svg', 'w').write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" shape-rendering="crispEdges">' + sym.strip() + '</svg>\n')
links = '\n'.join(f'<link rel="stylesheet" href="css/{n}.css">' for n in cssfiles)
html = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Triple A Sweeper</title>
<link rel="icon" href="favicon.svg">
<!-- @fonts:start (replaced by Google Fonts links in the single-file build) -->
<link rel="stylesheet" href="css/fonts.css">
<!-- @fonts:end -->
{links}
</head>
<body>
{body}

<script type="module" src="js/main.js"></script>
</body>
</html>
'''
open(WS + 'index.html', 'w').write(html)
# keep the Google Fonts block from the original for the single-file build
gf = src[src.index('<link rel="preconnect"'):src.index('<style>')].strip()
os.makedirs(WS + 'tools/build', exist_ok=True)
open(WS + 'tools/build/google-fonts.html', 'w').write(gf + '\n')
print('css', cssfiles)

# hand-written sources that live next to the generated modules
for f in glob.glob(SP + 'ws_src/**/*', recursive=True):
    if os.path.isfile(f):
        dst = WS + os.path.relpath(f, SP + 'ws_src')
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(f, dst)
