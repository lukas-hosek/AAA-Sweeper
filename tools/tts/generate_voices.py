#!/usr/bin/env python3
"""Generate voice lines with Kokoro TTS (offline, CPU) and register them in the game.

For every line in tools/tts/lines.py this writes public/voices/<id>.mp3 (mono, 24 kHz) and updates
js/data/voice-manifest.js (duration, and speaker + subtitle for batches 2+).

Usage (from the project root, with the venv active, see docs/SETUP.md):
    python3 tools/tts/generate_voices.py              # generate only lines that have no MP3 yet
    python3 tools/tts/generate_voices.py pa_5 pa_6    # (re)generate specific ids
    python3 tools/tts/generate_voices.py --force      # regenerate everything (about 5-10 minutes on a laptop CPU)
    python3 tools/tts/generate_voices.py --check      # only verify lines.py, MP3 files and manifest agree (no TTS)
    python3 tools/tts/generate_voices.py --say reyes "Any text"   # preview a voice into out/tts/preview.mp3

Adding a new line: append it to the newest batch in lines.py (or add a batch), run this script with the id,
then reference the id in js/data/dialogue.js (CHAT arcs, PIN, QUEST_ON_LINE ...) or from game code.
Kokoro is not deterministic across versions: regenerated lines will sound slightly different from the originals.
"""
import json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
VOICE_DIR = os.path.join(ROOT, 'public', 'voices')
MANIFEST = os.path.join(ROOT, 'js', 'data', 'voice-manifest.js')
MODELS = os.path.join(HERE, 'models')
MODEL = os.path.join(MODELS, 'kokoro-v1.0.int8.onnx')
VOICES_BIN = os.path.join(MODELS, 'voices-v1.0.bin')
PAD_SEC = 0.12   # silence appended to every line (keeps the radio squelch from clipping the last word)

sys.path.insert(0, HERE)
from lines import VOICE, BATCHES  # noqa: E402

HEAD = '''// data/voice-manifest.js — GENERATED by tools/tts/generate_voices.py. Do not edit by hand.
// One entry per voice line: d = duration in seconds, w = speaker key, t = subtitle text.
// Lines of the first batch have no w/t: their speaker comes from the id prefix (PREFIX) and
// their subtitle from SUBS in data/dialogue.js. Audio files live in public/voices/<id>.mp3.
export const VOICES={'''


def read_manifest():
    if not os.path.exists(MANIFEST):
        return {}
    src = open(MANIFEST, encoding='utf-8').read()
    body = src[src.index('export const VOICES={') + len('export const VOICES={'):src.rindex('};')]
    body = body.strip().rstrip(',')
    return json.loads('{' + body + '}') if body else {}


def write_manifest(m):
    rows = [f'{json.dumps(k)}:{json.dumps(m[k], ensure_ascii=False, separators=(",", ":"))},' for k in sorted(m)]
    open(MANIFEST, 'w', encoding='utf-8').write(HEAD + '\n' + '\n'.join(rows) + '\n};\n')


def all_lines():
    for b in BATCHES:
        for entry in b['lines']:
            lid, who, text = entry[0], entry[1], entry[2]
            disp = entry[3] if len(entry) > 3 else None
            yield b, lid, who, text, disp or text


def check():
    man, ok = read_manifest(), True
    ids = [l[1] for l in all_lines()]
    dup = {i for i in ids if ids.count(i) > 1}
    for i in sorted(dup):
        print('duplicate id in lines.py:', i); ok = False
    for b, lid, who, text, disp in all_lines():
        if who not in VOICE:
            print(f'{lid}: unknown speaker {who}'); ok = False
        if not os.path.exists(os.path.join(VOICE_DIR, lid + '.mp3')):
            print(f'{lid}: missing public/voices/{lid}.mp3'); ok = False
        if lid not in man:
            print(f'{lid}: missing from voice-manifest.js'); ok = False
        elif b['manifest_text'] and (man[lid].get('t') != disp or man[lid].get('w') != who):
            print(f'{lid}: manifest speaker/subtitle differs from lines.py'); ok = False
    for k in sorted(set(man) - set(ids)):
        print(f'{k}: in manifest but not in lines.py'); ok = False
    print('OK' if ok else 'PROBLEMS FOUND', f'({len(ids)} lines)')
    return ok


def synth(kokoro, who, text, mp3, bitrate):
    import numpy as np, soundfile as sf
    voice, speed = VOICE[who]
    s, sr = kokoro.create(text, voice=voice, speed=speed, lang='en-gb' if voice.startswith('b') else 'en-us')
    s = np.concatenate([s, np.zeros(int(sr * PAD_SEC), dtype=s.dtype)])
    with tempfile.TemporaryDirectory() as td:
        wav = os.path.join(td, 'line.wav')
        sf.write(wav, s, sr)
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-ar', '24000', '-b:a', bitrate, mp3], check=True)
    return round(len(s) / sr, 2)


def load_kokoro():
    if not (os.path.exists(MODEL) and os.path.exists(VOICES_BIN)):
        sys.exit('Kokoro model files missing. Run: bash tools/tts/download_models.sh')
    from kokoro_onnx import Kokoro
    return Kokoro(MODEL, VOICES_BIN)


def main(argv):
    if '--check' in argv:
        sys.exit(0 if check() else 1)
    if '--say' in argv:
        i = argv.index('--say'); who, text = argv[i + 1], argv[i + 2]
        os.makedirs(os.path.join(ROOT, 'out', 'tts'), exist_ok=True)
        out = os.path.join(ROOT, 'out', 'tts', 'preview.mp3')
        print(out, synth(load_kokoro(), who, text, out, '64k'), 's'); return
    force = '--force' in argv
    only = {a for a in argv if not a.startswith('--')}
    todo = [l for l in all_lines() if (l[1] in only) or (not only and (force or not os.path.exists(os.path.join(VOICE_DIR, l[1] + '.mp3'))))]
    unknown = only - {l[1] for l in all_lines()}
    if unknown:
        sys.exit('not in lines.py: ' + ', '.join(sorted(unknown)))
    if not todo:
        print('nothing to do (all lines have audio). Use ids or --force to regenerate.'); return
    kokoro, man = load_kokoro(), read_manifest()
    os.makedirs(VOICE_DIR, exist_ok=True)
    for b, lid, who, text, disp in todo:
        d = synth(kokoro, who, text, os.path.join(VOICE_DIR, lid + '.mp3'), b['bitrate'])
        man[lid] = {'d': d, 'w': who, 't': disp} if b['manifest_text'] else {'d': d}
        write_manifest(man)   # after every line, so an interrupted run keeps its progress
        print(f'{lid:10s} {d:5.2f}s  {who}: {disp[:70]}', flush=True)
    print(f'done: {len(todo)} line(s)')


if __name__ == '__main__':
    main(sys.argv[1:])
